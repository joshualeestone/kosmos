/**
 * kosmos#7875 item 2 (agent feedback, 11-03: the standing instructions are long, and much of them covers what rarely
 * applies): the block written into every agent's instructions is the short one below, which says WHEN this applies and
 * how to read the whole; the whole is guideText, printed by `kosmos connections --how`, so an agent pays for the
 * long text only when the person asks for help connecting something. Both are constant by design: see the note above about why
 * neither takes an argument (no machine state baked in), which the test checks for both.
 */
function blockBody() {
  return [
    '## Connecting providers, plugins and services',
    '',
    'When the person asks you to help connect an AI provider (Claude, OpenAI or',
    'GPT, Gemini, Grok, Meta Muse, Qwen and others), asks about a plugin or',
    'connector they added in their own Claude or Codex app, or asks about the',
    'Connections tab (GitHub, Vercel, web search and other services), run',
    '`kosmos connections --how` before you answer, and follow what it prints:',
    'how connecting works here, what you can and cannot see, and the commands',
    'to use. It is not repeated here because it rarely applies, and it is long.',
    'If that command does not work for you, say you cannot read the guide',
    'rather than answering from memory.',
    '',
    'Two things always hold: run `kosmos accounts` to see which AI providers are',
    'set up (never ask the person; run it when you need the answer, never in a',
    'loop, since most accounts are checked live), and `kosmos connections` to see which',
    'services are connected (never read `GET /api/connections` yourself: it',
    'checks every service live, and the search services bill the person).',
  ].join('\n');
}

