'use strict';

/**
 * O05: tools/lib/sbom.js derives a release's CycloneDX bill of materials from its signed manifest, the connector's
 * Cargo.lock and the tmux build pins. The git reads are injected here, so no relay checkout is needed.
 *
 *   node --test tools.sbom-o05.test.js
 */
const test = require('node:test');
const assert = require('node:assert/strict');

const { parseLock, closure, tmuxPins, build } = require('./tools/lib/sbom.js');

const SHA = (c) => c.repeat(64);
const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "kosmos-tunnel-client"
version = "0.1.0"
dependencies = [
 "kosmos-relay-proto",
 "rcgen 0.13.2",
 "rustls",
]

[[package]]
name = "kosmos-relay-proto"
version = "0.1.0"
dependencies = ["serde"]

[[package]]
name = "rcgen"
version = "0.12.1"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${SHA('1')}"

[[package]]
name = "rcgen"
version = "0.13.2"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${SHA('2')}"
dependencies = [
 "ring",
]

[[package]]
name = "ring"
version = "0.17.14"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${SHA('3')}"

[[package]]
name = "rustls"
version = "0.23.46"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${SHA('4')}"
dependencies = [
 "ring",
]

[[package]]
name = "serde"
version = "1.0.228"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${SHA('5')}"

[[package]]
name = "kosmos-relay"
version = "0.1.0"
dependencies = [
 "rcgen 0.12.1",
 "axum",
]

[[package]]
name = "axum"
version = "0.8.4"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${SHA('6')}"
`;
const TMUX = `#!/bin/bash
TMUX_VERSION="3.5a"
LIBEVENT_VERSION="2.1.12-stable"
NCURSES_VERSION="6.5"
TMUX_SHA="${SHA('a')}"
LIBEVENT_SHA="${SHA('b')}"
NCURSES_SHA="${SHA('c')}"
`;
const MANIFEST = {
  manifest: 1, version: '0.7.60', arch: 'arm64', sha256: SHA('d'),
  app: { commit: 'a'.repeat(40) }, node: { version: 'v24.19.0', download_sha256: SHA('e') },
  connector: { signed_sha256: SHA('f'), commit: 'b'.repeat(40) }, built: { at: '2026-10-19T17:00:00Z' },
};
const show = (files) => (repo, commit, file) => {
  const v = files[`${repo}:${commit}:${file}`];
  if (v === undefined) throw new Error(`no ${repo}:${commit}:${file}`);
  return v;
};
const FILES = { [`R:${'b'.repeat(40)}:Cargo.lock`]: LOCK, [`K:${'a'.repeat(40)}:tools/build-tmux-from-source.sh`]: TMUX };
const sbom = (m = MANIFEST, files = FILES) => build(m, { repo: 'K', relay: 'R', show: show(files) });
const names = (b) => b.components.map((c) => `${c.name}@${c.version}`);

test('the crate list is the closure from the connector: transitive crates in, the relay server\'s crates out', () => {
  const { deps } = closure(parseLock(LOCK), 'kosmos-tunnel-client');
  const got = deps.map((p) => `${p.name}@${p.version}`).sort();
  assert.deepEqual(got, ['kosmos-relay-proto@0.1.0', 'rcgen@0.13.2', 'ring@0.17.14', 'rustls@0.23.46', 'serde@1.0.228']);
});

test('a dependency named with its version resolves to that version, not the other one', () => {
  const n = names(sbom());
  assert.ok(n.includes('rcgen@0.13.2'));
  assert.ok(!n.includes('rcgen@0.12.1'), 'the relay server\'s rcgen must not be listed');
  assert.ok(!n.includes('axum@0.8.4'));
});

test('an unresolvable dependency refuses rather than listing less', () => {
  const lock = LOCK.replace('"rcgen 0.13.2"', '"rcgen 9.9.9"');
  assert.throws(() => closure(parseLock(lock), 'kosmos-tunnel-client'), /cannot resolve dependency "rcgen 9.9.9"/);
  assert.throws(() => closure(parseLock(LOCK.replace('"rcgen 0.13.2"', '"rcgen"')), 'kosmos-tunnel-client'), /cannot resolve/);
});

test('every component carries its version and hash; crates a purl; first-party crates none', () => {
  const b = sbom();
  assert.equal(b.bomFormat, 'CycloneDX');
  assert.equal(b.specVersion, '1.5');
  assert.equal(b.metadata.component.version, '0.7.60');
  const by = Object.fromEntries(b.components.map((c) => [c.name + '@' + c.version, c]));
  assert.deepEqual(by['node@24.19.0'].hashes, [{ alg: 'SHA-256', content: SHA('e') }]);
  assert.deepEqual(by['tmux@3.5a'].hashes, [{ alg: 'SHA-256', content: SHA('a') }]);
  assert.deepEqual(by['ncurses@6.5'].hashes, [{ alg: 'SHA-256', content: SHA('c') }]);
  assert.equal(by['rustls@0.23.46'].purl, 'pkg:cargo/rustls@0.23.46');
  assert.deepEqual(by['rustls@0.23.46'].hashes, [{ alg: 'SHA-256', content: SHA('4') }]);
  assert.equal(by['kosmos-relay-proto@0.1.0'].purl, undefined);
  assert.deepEqual(by['kosmos-tunnel-client@0.1.0'].hashes, [{ alg: 'SHA-256', content: SHA('f') }]);
  assert.equal(b.components.length, 10, names(b).join(' '));
});

test('the same release gives a byte-identical SBOM; another release a different serial', () => {
  assert.equal(JSON.stringify(sbom()), JSON.stringify(sbom()));
  assert.notEqual(sbom().serialNumber, sbom({ ...MANIFEST, sha256: SHA('9') }).serialNumber);
  assert.match(sbom().serialNumber, /^urn:uuid:[0-9a-f]{8}-[0-9a-f]{4}-5[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
});

test('a manifest with no connector commit, or a tmux script with no version, refuses', () => {
  assert.throws(() => sbom({ ...MANIFEST, connector: { signed_sha256: SHA('f') } }), /no app or connector commit/);
  assert.throws(() => tmuxPins(TMUX.replace(/^NCURSES_VERSION=.*$/m, '')), /no ncurses version/);
});
