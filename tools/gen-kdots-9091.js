#!/usr/bin/env node
// kosmos#9091: writes ios/Kosmos/KDots.swift from ios/LogicTests/hop/k-dots.json, the 153 dots measured off the app
// icon's K (centre x, centre y, radius, at the icon's 1024 scale, y down) and the icon's gold gradient. Run it after
// the JSON changes: node tools/gen-kdots-9091.js. ios/LogicTests/run-hop.sh fails if the two disagree.
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = JSON.parse(fs.readFileSync(path.join(root, 'ios/LogicTests/hop/k-dots.json'), 'utf8'));
const hex = (c) => '0x' + c.map((v) => v.toString(16).padStart(2, '0').toUpperCase()).join('');
const lines = src.dots.map(([x, y, r]) => `        (${x}, ${y}, ${r}),`);
const out = `// Generated by tools/gen-kdots-9091.js from ios/LogicTests/hop/k-dots.json. Do not edit by hand.
// kosmos#9091: the app icon's K as ${src.dots.length} measured dots (centre x, centre y, radius at the icon's ${src.size} scale, y down),
// and the icon's gold gradient, top to bottom. Hop draws its faint K, and lights it, from these.
enum KDots {
    static let size = ${src.size}.0
    static let top: UInt32 = ${hex(src.top)}
    static let bottom: UInt32 = ${hex(src.bot)}
    static let dots: [(x: Double, y: Double, r: Double)] = [
${lines.join('\n')}
    ]
}
`;
fs.writeFileSync(path.join(root, 'ios/Kosmos/KDots.swift'), out);
console.log(`wrote ios/Kosmos/KDots.swift: ${src.dots.length} dots`);
